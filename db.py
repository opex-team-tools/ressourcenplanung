    end = logic.month_end(today, 5)
    days = logic.workdays(start, end)
    rows = []
    for cid in cons:
        cur = start
        while cur < end:
            # Pipeline wird nach hinten dünner: realistische Kapazitätslücke ab ca. 8 Wochen
            if cur > today + dt.timedelta(weeks=8) and rng.random() < 0.45:
                cur += dt.timedelta(weeks=rng.randint(2, 5))
                continue
            pid = rng.choice(pids)
