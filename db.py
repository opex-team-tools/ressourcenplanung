def _slot(art: str, project_id) -> str:
    return f"p{int(project_id)}" if project_id is not None and art in logic.PROJEKT_ARTEN else art


def upsert_entries(rows: list[tuple], user: str) -> int:
    """rows: (consultant_id, tag, art, project_id | None, stunden). Gleiches Projekt am gleichen Tag
    wird aktualisiert (Ort, Stunden), andere Einträge des Tages bleiben bestehen."""
    ts = _now()
    data = [(int(c), t.isoformat(), _slot(a, p), a, None if p is None else int(p), float(h), user, ts)
            for c, t, a, p, h in rows]
    with connect() as con:
        con.executemany(
            """INSERT INTO entries(consultant_id, tag, slot, art, project_id, stunden, updated_by, updated_at)
               VALUES(?,?,?,?,?,?,?,?)
               ON CONFLICT(consultant_id, tag, slot) DO UPDATE SET
                 art=excluded.art, project_id=excluded.project_id, stunden=excluded.stunden,
                 updated_by=excluded.updated_by, updated_at=excluded.updated_at""", data)
    return len(data)


def set_week_target(cid: int, ws: dt.date, art: str, project_id, target_days: float, ort: str, user: str,
                    min_day: dt.date | None = None) -> int:
    """Setzt für eine Person und Woche die Tage eines Projekts bzw. einer Abwesenheit auf einen Zielwert.
    Verteilt auf freie Arbeitstage (Feiertage ausgenommen), baut bei Reduktion von Freitag her ab.
    min_day: nur Tage ab diesem Datum verändern (z. B. beim Verteilen ab heute)."""
    days = [ws + dt.timedelta(days=i) for i in range(5)]
    days = [d for d in days if not logic.feiertag_name(d) and (min_day is None or d >= min_day)]
    if not days:
        return 0
    slot = _slot(art, project_id) if project_id is None else f"p{int(project_id)}"
    e = entries(days[0], days[-1], consultant_id=cid)
    mine = e[e["slot"] == slot] if not e.empty else e
    other = e[e["slot"] != slot] if not e.empty else e
    m = mine.groupby("tag")["stunden"].sum().to_dict() if not mine.empty else {}
    o = other.groupby("tag")["stunden"].sum().to_dict() if not other.empty else {}
    arts = dict(zip(mine["tag"], mine["art"])) if not mine.empty else {}
    plan = logic.week_fill_plan(float(target_days) * logic.TAG_H, m, o, days)
    ups, dels = [], []
    for d, h in plan.items():
        if h <= 1e-9:
            dels.append((int(cid), d.isoformat(), slot))
        else:
            a = arts.get(d, ort if project_id is not None else art)
            ups.append((cid, d, a, project_id, h))
    if ups:
        upsert_entries(ups, user)
    if dels:
        with connect() as con:
            con.executemany("DELETE FROM entries WHERE consultant_id=? AND tag=? AND slot=?", dels)
    return len(plan)


def distribute_open(cid: int, project_id: int, tage: float, ab: dt.date, pro_woche: float, ort: str,
                    user: str, dry_run: bool = False) -> list[tuple[dt.date, float]]:
    """Verteilt offene Beratertage ab einer Woche mit x Tagen pro Woche. Rückgabe: [(montag, tage_neu_gesamt)]."""
    plan, rest, ws = [], float(tage), logic.monday(ab)
    e = entries(ab, ws + dt.timedelta(weeks=60), consultant_id=cid, project_id=project_id)
    cur = e.groupby(e["tag"].map(logic.monday))["stunden"].sum().to_dict() if not e.empty else {}
    for _ in range(60):
        if rest <= 1e-9:
            break
        cap = len([1 for i in range(5) if not logic.feiertag_name(ws + dt.timedelta(days=i))
                   and ws + dt.timedelta(days=i) >= ab])
        have = cur.get(ws, 0.0) / logic.TAG_H   # nur Tage ab 'ab' zählen
        put = min(max(min(pro_woche, cap) - have, 0.0), rest)
        if put > 1e-9:
            plan.append((ws, have, put))
            rest -= put
        ws += dt.timedelta(weeks=1)
    if not dry_run:
        for w, have, put in plan:
            set_week_target(cid, w, ort, project_id, have + put, ort, user, min_day=ab)
    return plan


