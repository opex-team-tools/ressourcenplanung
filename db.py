class _Conn:
    """Dünner Adapter: einheitliche ?-Platzhalter und Dict-Zeilen für beide Backends."""

    def __init__(self, raw, pg: bool):
        self.raw, self.pg = raw, pg
        self.wrote = False

    def _q(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.pg else sql

    def _mark(self, sql: str) -> None:
        if not sql.lstrip().upper().startswith(("SELECT", "PRAGMA")):
            self.wrote = True
            _bump()

    def execute(self, sql: str, params=()):
        self._mark(sql)
        if self.pg:
            cur = self.raw.cursor()
            cur.execute(self._q(sql), params)
            return cur
        return self.raw.execute(sql, params)

    def executemany(self, sql: str, seq):
        self._mark(sql)
        seq = list(seq)
        if not seq:
            return None
        if self.pg:
            cur = self.raw.cursor()
            cur.executemany(self._q(sql), seq)
            return cur
        return self.raw.executemany(sql, seq)

    def insert_id(self, sql: str, params=()) -> int:
        return self.execute(sql + " RETURNING id", params).fetchone()["id"]

    def script(self, sql: str) -> None:
        for stmt in (x.strip() for x in sql.split(";")):
            if stmt:
                self.execute(stmt)


_pool = None
_pool_lock = threading.Lock()


def _get_pool():
    global _pool
    with _pool_lock:
        if _pool is None:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
            # prepare_threshold=None: kompatibel mit Supabase Pooler
            _pool = ConnectionPool(db_url(), min_size=1, max_size=5, open=True, timeout=20,
                                   kwargs={"row_factory": dict_row, "prepare_threshold": None,
                                           "connect_timeout": 10})
        return _pool


@contextmanager
def connect():
    if is_pg():
        with _get_pool().connection() as raw:  # Commit bei Erfolg, Rollback bei Fehler
            c = _Conn(raw, True)
            yield c
        if c.wrote:
            _bump()  # nach dem Commit nochmals invalidieren
        return
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    con = sqlite3.connect(DB_PATH, timeout=15)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA journal_mode=WAL")
    con.execute("PRAGMA foreign_keys=ON")
    c = _Conn(con, False)
    try:
        yield c
        con.commit()
    finally:
        con.close()
        if c.wrote:
            _bump()


# ---------------------------------------------------------------- Lese-Cache
# Jede Seite liest dieselben Tabellen mehrfach; jede Abfrage nach Supabase kostet ~100 ms.
# Lesezugriffe werden deshalb im Serverprozess zwischengespeichert. Jede Schreiboperation (egal von wem)
# erhöht die Version und macht den Cache sofort ungültig. Alle Nutzer teilen sich denselben Prozess.
_CACHE: dict = {}
_CACHE_LOCK = threading.Lock()
_VERSION = [0]
CACHE_TTL = float(os.environ.get("CACHE_TTL", "300"))  # Sicherheitsnetz für Änderungen außerhalb der App
_STATS = {"hit": 0, "miss": 0}


def _bump() -> None:
    with _CACHE_LOCK:
        _VERSION[0] += 1
        _CACHE.clear()


def _df(sql: str, params=()) -> pd.DataFrame:
    key = (sql, tuple(params))
    now = __import__("time").monotonic()
    with _CACHE_LOCK:
        hit = _CACHE.get(key)
        ver = _VERSION[0]
    if hit is not None and hit[0] == ver and now - hit[1] < CACHE_TTL:
        _STATS["hit"] += 1
        return hit[2].copy()
    _STATS["miss"] += 1
    with connect() as con:
        cur = con.execute(sql, params)
        rows = cur.fetchall()
        cols = [d[0] for d in cur.description]
    df = pd.DataFrame([tuple(r.values()) if isinstance(r, dict) else tuple(r) for r in rows], columns=cols)
    with _CACHE_LOCK:
        if _VERSION[0] == ver:  # nur cachen, wenn zwischendurch niemand geschrieben hat
            if len(_CACHE) > 400:
                _CACHE.clear()
            _CACHE[key] = (ver, now, df)
    return df.copy()


def _now() -> str:
    return dt.datetime.now().isoformat(timespec="seconds")


