def _add_col(con, table: str, col: str, typ: str) -> None:
    if con.pg:
        con.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {col} {typ}")
    else:
        cols = [r["name"] for r in con.execute(f"PRAGMA table_info({table})").fetchall()]
        if col not in cols:
            con.execute(f"ALTER TABLE {table} ADD COLUMN {col} {typ}")


def _migrate(con) -> None:
    """Nachträgliche Spalten und Übernahme der alten Tagesbuchungen (8 h je Tag)."""
    _add_col(con, "consultants", "vollname", "TEXT")
    _add_col(con, "consultants", "tagessatz", "REAL")
    _add_col(con, "consultants", "bereich", "TEXT")
    _add_col(con, "akquise", "bereich", "TEXT")
    # Bereich umbenannt: Sales Excellence heißt Service Excellence
    for t in ("consultants", "akquise"):
        con.execute(f"UPDATE {t} SET bereich=? WHERE bereich=?", ("Service Excellence", "Sales Excellence"))
    _add_col(con, "positionen", "zielauslastung", "REAL")
    _add_col(con, "projects", "leiter_id", "INTEGER")
    n_new = con.execute("SELECT COUNT(*) AS n FROM entries").fetchone()["n"]
    n_old = con.execute("SELECT COUNT(*) AS n FROM bookings").fetchone()["n"]
    if n_new or not n_old:
        return
    con.execute("""INSERT INTO entries(consultant_id, tag, slot, art, project_id, stunden, updated_by, updated_at)
                   SELECT consultant_id, tag,
                          CASE WHEN project_id IS NULL THEN art ELSE 'p' || project_id END,
                          art, project_id, 8, updated_by, updated_at
                   FROM bookings""")
    # Budget je Berater: Projektbudget anteilig nach bisher gebuchten Tagen verteilen
    pairs = con.execute("""SELECT b.project_id AS pid, b.consultant_id AS cid, COUNT(*) AS n,
                                  COALESCE(p.budget_tage, 0) AS budget
                           FROM bookings b JOIN projects p ON p.id = b.project_id
                           WHERE b.project_id IS NOT NULL
                           GROUP BY b.project_id, b.consultant_id, p.budget_tage""").fetchall()
    total = {}
    for r in pairs:
        total[r["pid"]] = total.get(r["pid"], 0) + r["n"]
    for r in pairs:
        b = r["budget"] * r["n"] / total[r["pid"]] if r["budget"] else r["n"]
        con.execute("INSERT INTO project_members(project_id, consultant_id, budget_tage) VALUES(?,?,?) "
                    "ON CONFLICT(project_id, consultant_id) DO NOTHING", (r["pid"], r["cid"], round(b * 2) / 2))


