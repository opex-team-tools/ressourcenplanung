def _pnorm(s: str) -> list[str]:
    """Personennamen normalisieren: Kleinschrift, Umlaute, Satzzeichen weg, Reihenfolge egal."""
    s = s if isinstance(s, str) else ""
    s = s.lower().translate(_UML).replace(",", " ")
    return sorted(t for t in re.split(r"[^a-z0-9]+", s) if t)


def find_consultant(text: str):
    """Findet einen aktiven Mitarbeiter über 'Vorname Nachname', 'Nachname, Vorname' oder Kürzel."""
    q = _pnorm(text)
    if not q:
        return None
    for r in consultants().to_dict("records"):
        if q == _pnorm(r.get("name")) or q == _pnorm(r.get("vollname")):
            return r
    return None


def suggest_kuerzel(vollname: str) -> str:
    """Muster: 1. Buchstabe Vorname + 2 Buchstaben Nachname (z. B. Max Mustermann = mmu)."""
    t = [x for x in re.split(r"[^a-z]+", (vollname or "").lower().translate(_UML)) if x]
    base = (t[0][0] + t[-1][:2]) if len(t) >= 2 else (t[0][:3] if t else "neu")
    taken = {str(x).lower() for x in consultants(active_only=False)["name"]}
    k, i = base, 2
    while k in taken:
        k, i = f"{base}{i}", i + 1
    return k


def create_consultant(name: str, vollname: str = "", rolle: str = "",
                      tagessatz: float | None = None) -> tuple[int, bool]:
    """Legt einen Mitarbeiter an oder reaktiviert ihn. Rückgabe: (id, neu_angelegt)."""
    name = name.strip()
    ts = float(tagessatz) if tagessatz else None
    with connect() as con:
        row = con.execute("SELECT id FROM consultants WHERE LOWER(name)=LOWER(?)", (name,)).fetchone()
        if row:
            con.execute("UPDATE consultants SET aktiv=1, vollname=COALESCE(NULLIF(?, ''), vollname), "
                        "rolle=COALESCE(NULLIF(?, ''), rolle), tagessatz=COALESCE(?, tagessatz) WHERE id=?",
                        (vollname, rolle, ts, row["id"]))
            return row["id"], False
        nxt = con.execute("SELECT COALESCE(MAX(sort), -1) + 1 AS n FROM consultants").fetchone()["n"]
        return con.insert_id("INSERT INTO consultants(name, vollname, rolle, tagessatz, sort) VALUES(?,?,?,?,?)",
                             (name, vollname or None, rolle or None, ts, nxt)), True


def update_project_meta(project_id: int, start: dt.date | None = None, ende: dt.date | None = None,
                        leiter_id: int | None = None, aktiv: bool | None = None) -> None:
    sets, params = [], []
    for col, v in (("start", start), ("ende", ende)):
        if v is not None:
            sets.append(f"{col}=?"); params.append(v.isoformat())
    if leiter_id is not None:
        sets.append("leiter_id=?"); params.append(int(leiter_id))
    if aktiv is not None:
        sets.append("aktiv=?"); params.append(1 if aktiv else 0)
    if sets:
        with connect() as con:
            con.execute(f"UPDATE projects SET {', '.join(sets)} WHERE id=?", params + [int(project_id)])


