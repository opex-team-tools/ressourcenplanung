def db_url() -> str:
    return os.environ.get("DATABASE_URL", "").strip()


def is_pg() -> bool:
    return db_url().startswith(("postgres://", "postgresql://"))


def backend() -> str:
    return "Postgres" if is_pg() else "SQLite (lokal)"


class _Conn:
    """Dünner Adapter: einheitliche ?-Platzhalter und Dict-Zeilen für beide Backends."""

    def __init__(self, raw, pg: bool):
        self.raw, self.pg = raw, pg

    def _q(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.pg else sql

    def execute(self, sql: str, params=()):
        if self.pg:
            cur = self.raw.cursor()
            cur.execute(self._q(sql), params)
            return cur
        return self.raw.execute(sql, params)

    def executemany(self, sql: str, seq):
        seq = list(seq)
        if not seq:
            return None
        if self.pg:
            cur = self.raw.cursor()
            cur.executemany(self._q(sql), seq)
            return cur
        return self.raw.executemany(sql, seq)

    def insert_id(self, sql: str, params=()) -> int:
        return self.execute(sql + " RETURNING id", params).fetchone()["id"]

    def script(self, sql: str) -> None:
        for stmt in (x.strip() for x in sql.split(";")):
            if stmt:
                self.execute(stmt)


_pool = None
_pool_lock = threading.Lock()


def _get_pool():
    global _pool
    with _pool_lock:
        if _pool is None:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
            # prepare_threshold=None: kompatibel mit Supabase Pooler
            _pool = ConnectionPool(db_url(), min_size=1, max_size=5, open=True, timeout=20,
                                   kwargs={"row_factory": dict_row, "prepare_threshold": None,
                                           "connect_timeout": 10})
        return _pool


@contextmanager
def connect():
    if is_pg():
        with _get_pool().connection() as raw:  # Commit bei Erfolg, Rollback bei Fehler
            yield _Conn(raw, True)
        return
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    con = sqlite3.connect(DB_PATH, timeout=15)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA journal_mode=WAL")
    con.execute("PRAGMA foreign_keys=ON")
    try:
        yield _Conn(con, False)
        con.commit()
    finally:
        con.close()


def _df(sql: str, params=()) -> pd.DataFrame:
    with connect() as con:
        cur = con.execute(sql, params)
        rows = cur.fetchall()
        cols = [d[0] for d in cur.description]
    return pd.DataFrame([tuple(r.values()) if isinstance(r, dict) else tuple(r) for r in rows], columns=cols)


def _now() -> str:
    return dt.datetime.now().isoformat(timespec="seconds")


def demo_enabled() -> bool:
    return os.environ.get("DEMO_DATEN", "true").strip().lower() in ("1", "true", "ja", "yes")


def _add_col(con, table: str, col: str, typ: str) -> None:
    if con.pg:
        con.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {col} {typ}")
    else:
        cols = [r["name"] for r in con.execute(f"PRAGMA table_info({table})").fetchall()]
        if col not in cols:
            con.execute(f"ALTER TABLE {table} ADD COLUMN {col} {typ}")


def _migrate(con) -> None:
    """Nachträgliche Spalten und Übernahme der alten Tagesbuchungen (8 h je Tag)."""
    _add_col(con, "consultants", "vollname", "TEXT")
    _add_col(con, "projects", "leiter_id", "INTEGER")
    n_new = con.execute("SELECT COUNT(*) AS n FROM entries").fetchone()["n"]
    n_old = con.execute("SELECT COUNT(*) AS n FROM bookings").fetchone()["n"]
    if n_new or not n_old:
        return
    con.execute("""INSERT INTO entries(consultant_id, tag, slot, art, project_id, stunden, updated_by, updated_at)
                   SELECT consultant_id, tag,
                          CASE WHEN project_id IS NULL THEN art ELSE 'p' || project_id END,
                          art, project_id, 8, updated_by, updated_at
                   FROM bookings""")
    # Budget je Berater: Projektbudget anteilig nach bisher gebuchten Tagen verteilen
    pairs = con.execute("""SELECT b.project_id AS pid, b.consultant_id AS cid, COUNT(*) AS n,
                                  COALESCE(p.budget_tage, 0) AS budget
                           FROM bookings b JOIN projects p ON p.id = b.project_id
                           WHERE b.project_id IS NOT NULL
                           GROUP BY b.project_id, b.consultant_id, p.budget_tage""").fetchall()
    total = {}
    for r in pairs:
        total[r["pid"]] = total.get(r["pid"], 0) + r["n"]
    for r in pairs:
        b = r["budget"] * r["n"] / total[r["pid"]] if r["budget"] else r["n"]
        con.execute("INSERT INTO project_members(project_id, consultant_id, budget_tage) VALUES(?,?,?) "
                    "ON CONFLICT(project_id, consultant_id) DO NOTHING", (r["pid"], r["cid"], round(b * 2) / 2))


def init_db(seed: bool | None = None, team: list[str] | None = None) -> None:
    """team: Kürzel des echten Teams; werden beim allerersten Start angelegt."""
    seed = demo_enabled() if seed is None else seed
    with connect() as con:
        con.script(SCHEMA.replace("{PK}", PK["pg" if con.pg else "sqlite"]))
