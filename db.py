def entries(start: dt.date | None = None, end: dt.date | None = None, consultant_id: int | None = None,
            project_id: int | None = None, project_only: bool = False) -> pd.DataFrame:
    """Planungseinträge (mehrere je Tag möglich, in Stunden)."""
    cond, params = [], []
    if start:
        cond.append("e.tag >= ?"); params.append(start.isoformat())
    if end:
        cond.append("e.tag <= ?"); params.append(end.isoformat())
    if consultant_id is not None:
        cond.append("e.consultant_id = ?"); params.append(int(consultant_id))
    if project_id is not None:
        cond.append("e.project_id = ?"); params.append(int(project_id))
    if project_only:
        cond.append("e.project_id IS NOT NULL")
    where = ("WHERE " + " AND ".join(cond)) if cond else ""
    df = _df(f"""SELECT e.*, k.name FROM entries e
                 JOIN consultants k ON k.id = e.consultant_id {where}""", params)
    df["tag"] = pd.to_datetime(df["tag"]).dt.date
    df["stunden"] = pd.to_numeric(df["stunden"]).astype(float)
    return df


