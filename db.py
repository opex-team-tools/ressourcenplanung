def import_startdaten(team: list[dict], projekte: list[dict], budgets: list[dict], planung: list[dict],
                      user: str, replace: bool = True, val_rows: list[dict] | None = None,
                      positionen_neu: list[dict] | None = None) -> dict:
    """Übernimmt Startdaten (Team, Projekte, Budgets, Tageseinträge). replace=True löscht vorher alle
    Planungsdaten inkl. Testdaten; Mitarbeiter, die nicht im Team stehen, werden deaktiviert."""
    if replace:
        reset_planning()
    kz_ids = {}
    for i, t in enumerate(team):
        cid_, _ = create_consultant(t["kuerzel"], t.get("name") or "", t.get("rolle") or "")
        with connect() as con:
            con.execute("UPDATE consultants SET sort=? WHERE id=?", (i, cid_))
        kz_ids[t["kuerzel"].lower()] = cid_
    if replace and kz_ids:
        with connect() as con:
            for r in con.execute("SELECT id, name FROM consultants").fetchall():
                if r["name"].lower() not in kz_ids:
                    con.execute("UPDATE consultants SET aktiv=0 WHERE id=?", (r["id"],))
    allc = consultants(active_only=False)
    kz_ids.update({str(n).lower(): int(i) for n, i in zip(allc["name"], allc["id"])})
    clients_ = {}
    pids = {}
    for p in projekte:
        k = p["kunde"].strip()
        if k not in clients_:
            hit = match_client(k)
            clients_[k] = int(hit["id"]) if hit is not None and hit["name"] == k else create_client(k, p.get("website") or "")
        pid = ensure_project(clients_[k], p["projekt"])
        lid = kz_ids.get(str(p.get("leitung") or "").lower())
        update_project_meta(pid, start=p.get("start"), ende=p.get("ende"), leiter_id=lid, aktiv=True)
        with connect() as con:
            con.execute("UPDATE projects SET budget_tage=? WHERE id=?", (float(p.get("budget") or 0), pid))
        pids[(k, p["projekt"].strip())] = pid
    for b in budgets:
        pid = pids.get((b["kunde"].strip(), b["projekt"].strip()))
        cid_ = kz_ids.get(b["kuerzel"].lower())
        if pid and cid_:
            with connect() as con:
                con.execute("INSERT INTO project_members(project_id, consultant_id, budget_tage) VALUES(?,?,?) "
                            "ON CONFLICT(project_id, consultant_id) DO UPDATE SET budget_tage=excluded.budget_tage",
                            (pid, cid_, float(b["budget"] or 0)))
    rows, skipped = [], 0
    for e in planung:
        cid_ = kz_ids.get(e["kuerzel"].lower())
        pid = pids.get(((e.get("kunde") or "").strip(), (e.get("projekt") or "").strip())) if e.get("kunde") else None
        if not cid_ or (e.get("kunde") and not pid):
            skipped += 1
            continue
        rows.append((cid_, e["datum"], e["art"], pid, float(e["stunden"])))
    # gleiche Person/Tag/Slot zusammenfassen
    agg = {}
    for c, d, a, p, h in rows:
        k_ = (c, d, _slot(a, p))
        agg[k_] = (c, d, a, p, agg.get(k_, (0, 0, 0, 0, 0))[4] + h)
    upsert_entries(list(agg.values()), user)
    for p in positionen_neu or []:
        save_position(p["name"], p.get("tagessatz"), None, p.get("ziel"))
    n_val = 0
    if val_rows:
        ts = _now()
        with connect() as con:
            for v in val_rows:
                cid_ = kz_ids.get(str(v["kuerzel"]).lower())
                pid = pids.get((v["kunde"].strip(), v["projekt"].strip()))
                if not cid_ or not pid:
                    continue
                con.execute("INSERT INTO val(consultant_id, monat, project_id, tage, updated_by, updated_at) "
                            "VALUES(?,?,?,?,?,?) ON CONFLICT(consultant_id, monat, project_id) DO UPDATE SET "
                            "tage=excluded.tage", (cid_, v["monat"].replace(day=1).isoformat(), pid,
                                                   float(v["tage"] or 0), user, ts))
                n_val += 1
    return {"team": len(team), "projekte": len(pids), "budgets": len(budgets), "eintraege": len(agg),
            "uebersprungen": skipped, "val": n_val}


