def seed_demo(team_kuerzel: list[str] | None = None) -> None:
    today = dt.date.today()
    team = [("Max", "", "Senior Consultant"), ("Anna", "", "Projektleiterin"),
            ("Ben", "", "Consultant"), ("Clara", "", "Senior Consultant"),
            ("David", "", "Consultant"), ("Eva", "", "Projektleiterin"),
            ("Felix", "", "Consultant"), ("Hannah", "", "Senior Consultant"),
            ("Jonas", "", "Consultant"), ("Lena", "", "Consultant")]
    # Fiktive Demo-Kunden (keine echten Mandanten)
    kunden = [("Alpenwerk Maschinenbau", "", "Alpenwerk", "S&OP Einführung"),
              ("Isartal Chemie", "", "ITC", "Footprint Analyse"),
              ("Brennerhof Möbel", "", "BHM", "Baukasten Portfolio"),
              ("Donaumetall", "", "DM", "Szenarien Produktion"),
              ("Nordstern Logistik", "", "", "Lageroptimierung"),
              ("Bergmann Medizintechnik", "", "BMT", "OpEx Programm"),
              ("Kessler Antriebe", "", "", "Supply Chain")]
    if team_kuerzel:
        team = [(k, "", "") for k in team_kuerzel]
    rng = random.Random(42)
    with connect() as con:
        for i, (n, v, r) in enumerate(team):
            con.execute("INSERT INTO consultants(name,vollname,rolle,sort) VALUES(?,?,?,?)",
                        (n, v or None, r or None, i))
        pids = []
        for name, dom, ali, proj in kunden:
            cid = con.insert_id("INSERT INTO clients(name,domain,aliases) VALUES(?,?,?)", (name, dom, ali))
            pids.append(con.insert_id("INSERT INTO projects(client_id,name) VALUES(?,?)", (cid, proj)))
        cons = [r["id"] for r in con.execute("SELECT id FROM consultants ORDER BY id").fetchall()]

    start = logic.monday(today) - dt.timedelta(weeks=8)
    end = logic.month_end(today, 5)
    days = logic.workdays(start, end)
    changes = []
    for cid in cons:
        cur = start
        while cur < end:
            # Pipeline wird nach hinten dünner: realistische Kapazitätslücke ab ca. 8 Wochen
            if cur > today + dt.timedelta(weeks=8) and rng.random() < 0.45:
                cur += dt.timedelta(weeks=rng.randint(2, 5))
                continue
            pid = rng.choice(pids)
            stop = cur + dt.timedelta(weeks=rng.randint(4, 10))
            for d in (x for x in days if cur <= x < stop):
                if d.weekday() <= 3:
                    art = "Vor Ort" if rng.random() > 0.1 else "Remote"
                else:
                    art = rng.choice(["Remote", "Intern", "Remote", "Akquise"])
                changes.append((cid, d, art, pid if art in logic.PROJEKT_ARTEN else None))
            cur = stop
        urlaub = logic.monday(today) + dt.timedelta(weeks=rng.randint(1, 14))
        for d in (x for x in days if urlaub <= x < urlaub + dt.timedelta(days=5)):
            changes.append((cid, d, "Urlaub", None))
    write_cells(changes, "Demo")

    with connect() as con:
        for pid in pids:
            row = con.execute("""SELECT MIN(tag) s, MAX(tag) e, COUNT(*) n FROM bookings
                                 WHERE project_id=?""", (pid,)).fetchone()
            budget = round((row["n"] or 0) * rng.uniform(0.9, 1.3) / 5) * 5
            con.execute("UPDATE projects SET start=?, ende=?, budget_tage=? WHERE id=?",
                        (row["s"], row["e"], budget, pid))
