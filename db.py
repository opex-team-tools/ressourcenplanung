def save_akquise(rows: list[dict], user: str) -> None:
    """rows: id (None = neu), kunde, thema, stufe, val_tage, mt_tage, wahrscheinlichkeit, von, bis, team (Liste Kürzel).
    Zeilen, die nicht mehr vorkommen, werden archiviert."""
    ts = _now()

    def d(v):
        return v.isoformat() if isinstance(v, dt.date) else None

    def f(v):
        try:
            return None if v is None or pd.isna(v) else float(v)
        except (TypeError, ValueError):
            return None
    keep = set()
    with connect() as con:
        for r in rows:
            vals = (str(r["kunde"]).strip(), r.get("thema") or None, r.get("stufe") or None, f(r.get("val_tage")),
                    f(r.get("mt_tage")), f(r.get("wahrscheinlichkeit")), d(r.get("von")), d(r.get("bis")),
                    ",".join(r.get("team") or []), user, ts)
